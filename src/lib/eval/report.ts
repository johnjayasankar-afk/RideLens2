/**
 * The calibration report, written so that a bad result is as legible as a good
 * one.
 *
 * A product that publishes its own error rate is more credible than one that
 * does not — but only if the document is capable of saying "we do not know".
 * With an empty corpus this prints exactly that, at the top, rather than a
 * page of dashes that reads like a system still warming up.
 */
import { MODEL_VERSION } from "@/lib/sources/ratecard/model-params";

import type { Corpus } from "./corpus";
import { MIN_SAMPLES, type EvalReport, type Summary } from "./metrics";

const pct = (v: number | null): string => (v === null ? "—" : `${(v * 100).toFixed(1)}%`);
const money = (v: number | null): string => (v === null ? "—" : `$${(v / 100).toFixed(2)}`);
const signed = (v: number | null): string =>
  v === null ? "—" : `${v >= 0 ? "+" : "−"}$${Math.abs(v / 100).toFixed(2)}`;

function summaryRow(label: string, s: Summary): string {
  if (s.n < MIN_SAMPLES) {
    return `| ${label} | ${s.n} | _withheld — under ${MIN_SAMPLES}_ | | | |`;
  }
  return `| ${label} | ${s.n} | ${pct(s.coverage)} | ${pct(s.meanRelativeWidth)} | ${signed(
    s.biasMinor,
  )} | ${money(s.maeMinor)} |`;
}

const HEAD =
  "| Slice | n | Coverage | Mean width | Bias | MAE |\n| --- | ---: | ---: | ---: | ---: | ---: |";

export function renderReport(report: EvalReport, corpus: Corpus): string {
  const { overall } = report;
  const enough = overall.n >= MIN_SAMPLES;

  const lines: string[] = [
    "# Calibration",
    "",
    "<!-- Generated by `npm run eval`. Do not edit by hand. -->",
    "",
    `Generated **${report.generatedAt}** against model \`${MODEL_VERSION}\`.`,
    "",
  ];

  if (!enough) {
    lines.push(
      "## Not enough data to say anything yet",
      "",
      `The corpus holds **${overall.n}** scorable record${overall.n === 1 ? "" : "s"}. ` +
        `Nothing is reported below ${MIN_SAMPLES}, because a number on a page gets read ` +
        "and a caveat beside it does not.",
      "",
      "This is the honest state of the product today: the model has never been " +
        "measured against a real fare. See `docs/COLLECTION_PROTOCOL.md` for how to " +
        "start filling it.",
      "",
    );
  } else {
    lines.push(
      "## Headline",
      "",
      `Our band contained the actual fare in **${pct(overall.coverage)}** of ` +
        `**${overall.n}** reported rides, with a mean band width of ` +
        `**${pct(overall.meanRelativeWidth)}** of the fare.`,
      "",
      "Both numbers matter. A band of $5–$500 would score perfect coverage and be " +
        "worthless, so neither is ever published without the other.",
      "",
      `Coverage-adjusted sharpness: **${report.score === null ? "—" : report.score.toFixed(3)}**. ` +
        "This is the number a parameter change has to improve; it cannot be raised by " +
        "widening the band.",
      "",
    );
  }

  lines.push(
    "## Where the ground truth came from",
    "",
    "| Origin | Records | Counts toward coverage? |",
    "| --- | ---: | --- |",
    `| Rider-reported actuals | ${corpus.byOrigin.reported} | Yes |`,
    `| Manual collection protocol | ${corpus.byOrigin.manual} | Yes |`,
    `| Published aggregates | ${corpus.byOrigin.published} | No — distributional sanity check only |`,
    "",
    "Ground truth is never synthesised from the model. A corpus generated by the " +
      "thing it scores produces perfect calibration and means nothing.",
    "",
  );

  if (corpus.rejected.length > 0) {
    lines.push(
      `**${corpus.rejected.length} record${corpus.rejected.length === 1 ? "" : "s"} rejected.** ` +
        "Listed rather than dropped, because a corpus that silently shrinks is one whose " +
        "sample size is a lie.",
      "",
      ...corpus.rejected.slice(0, 10).map((r) => `- ${r.reason}`),
      "",
    );
  }

  lines.push("## Overall", "", HEAD, summaryRow("All", overall), "");

  if (report.curve.length > 0) {
    lines.push(
      "## Calibration curve",
      "",
      "Each band squeezed toward its centre, and how often the actual still landed " +
        "inside. A well-shaped band loses coverage smoothly; one that falls off a cliff " +
        "near the centre is wide for no reason.",
      "",
      "| Band kept | Coverage |",
      "| ---: | ---: |",
      ...report.curve.map(
        (p) => `| ${(p.bandFraction * 100).toFixed(0)}% | ${pct(p.observedCoverage)} |`,
      ),
      "",
    );
  }

  const titles: Record<string, string> = {
    provider: "By provider",
    marketId: "By market",
    hour: "By hour (UTC)",
    distanceBand: "By trip distance",
  };
  for (const [key, rows] of Object.entries(report.slices)) {
    if (rows.length === 0) continue;
    lines.push(
      `## ${titles[key] ?? key}`,
      "",
      HEAD,
      ...rows.map((r) => summaryRow(r.group, r.summary)),
      "",
    );
  }

  if (report.modelVersions.length > 1) {
    lines.push(
      "## Mixed model versions",
      "",
      `This corpus spans ${report.modelVersions.length} parameter sets: ` +
        `${report.modelVersions.map((v) => `\`${v}\``).join(", ")}. ` +
        "Compare them separately before drawing a conclusion — a change in the numbers " +
        "above may be a change in the model rather than in the world.",
      "",
    );
  }

  lines.push(
    "## What a bad result means",
    "",
    "- **Low coverage, narrow bands** — the model is confidently wrong. Widen, then fix.",
    "- **High coverage, wide bands** — the bands are hedging. Sharpen without losing coverage.",
    "- **Positive bias** — we underquote, and riders pay more than we said.",
    "- **Negative bias** — we overquote, and the product looks expensive.",
    "- **A slice far off the overall** — that market, provider or hour needs its own attention.",
    "",
  );

  return lines.join("\n");
}
