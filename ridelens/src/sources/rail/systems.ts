/**
 * Regional rail systems RideLens can price, and the tables it prices them from.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ PROVENANCE                                                               │
 * │                                                                          │
 * │ Fares are transcribed from each operator's own published table, with the │
 * │ date they were checked. Station coordinates, fare zones, line membership │
 * │ and scheduled run times come from the operator's published GTFS feed.    │
 * │                                                                          │
 * │ WHY THE FARES ARE NOT READ FROM THE FEED                                 │
 * │ Some feeds carry fare files, and they go stale. Metra's `fare_attributes │
 * │ .txt` is dated January 2024; its stops file was rebuilt in July 2026.    │
 * │ Reading fares straight out of a feed looks like the rigorous option and  │
 * │ is the one that silently ships last year's prices. The geometry — where  │
 * │ a station is, which zone it is in, which trains call there — is what a   │
 * │ schedule feed is actually authoritative for, and that is all it is used  │
 * │ for here. Every price was read off the operator's live fare page and     │
 * │ carries `verifiedOn`.                                                    │
 * │                                                                          │
 * │ `medianRunSeconds` is the median scheduled journey to the city terminal  │
 * │ across every direct train in the timetable — a published number, not a   │
 * │ speed estimate. Stations with no through service carry null rather than  │
 * │ a fabricated connection.                                                 │
 * │                                                                          │
 * │ ZONES ARE NOT DISTANCES. Metro-North zone 4 costs $10.25 off-peak        │
 * │ whether the rider boards at Scarsdale or White Plains. Nothing here      │
 * │ interpolates between stations.                                           │
 * └──────────────────────────────────────────────────────────────────────────┘
 */
