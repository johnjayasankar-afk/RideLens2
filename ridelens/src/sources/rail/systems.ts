/**
 * Cheap pre-filter: is either endpoint anywhere near this railroad at all?
 *
 * Saves walking three hundred stations for a trip in San Francisco, and keeps
 * the "no railroad here" message honest rather than reporting a 3000km walk to
 * the nearest platform.
 */
export function systemsNear(pickup: Point, destination: Point): RailSystem[] {
  return RAIL_SYSTEMS.filter((system) => {
    const box = boundsOf(system);
    return inLooseBox(pickup, box) || inLooseBox(destination, box);
  });
}

interface LooseBox {
  minLat: number;
  maxLat: number;
  minLng: number;
  maxLng: number;
}

const boundsCache = new WeakMap<RailSystem, LooseBox>();

function boundsOf(system: RailSystem): LooseBox {
  const cached = boundsCache.get(system);
  if (cached !== undefined) return cached;
  let minLat = 90;
  let maxLat = -90;
  let minLng = 180;
  let maxLng = -180;
  for (const s of system.stations) {
    minLat = Math.min(minLat, s.lat);
    maxLat = Math.max(maxLat, s.lat);
    minLng = Math.min(minLng, s.lng);
    maxLng = Math.max(maxLng, s.lng);
  }
  // ~0.12 degrees of slack, a little more than the widest station access radius.
  const box = {
    minLat: minLat - 0.12,
    maxLat: maxLat + 0.12,
    minLng: minLng - 0.12,
    maxLng: maxLng + 0.12,
  };
  boundsCache.set(system, box);
  return box;
}

function inLooseBox(p: Point, b: LooseBox): boolean {
  return p.lat >= b.minLat && p.lat <= b.maxLat && p.lng >= b.minLng && p.lng <= b.maxLng;
}
